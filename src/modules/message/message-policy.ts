/**
 * 站内信的发送策略常量（跨模块共用，故单独成文件）
 *
 * ── A 规则：扫描类消息的静默期（§4.2.5）─────────────────────────────────────
 * 「下单 2 小时内不推送」。作用域**仅限 T1/T2 两条扫描类消息**
 * （`ORDER_EXPIRED` / `ORDER_EXPIRE_REMINDER`）：
 *
 *   · 用户刚下完单，App 还开着，此时推「您的订单已过期」是纯粹的骚扰；
 *   · 退款受理 / 审核结果、管理员回复、反馈回应**一律不套此规则**——
 *     它们是对用户**主动动作**的应答，压 2 小时会出现「申请了退款却迟迟收不到审核结果」，
 *     这是比打扰严重得多的问题。
 *
 * 这个值只在 `findExpiredNotNotified` / `findTodayUnverified` 两条查询里生效。
 * 查询本身不再 import 本常量，而是接收 `quietWindowMs` 参数——因为手动触发可以覆盖
 * （见下），默认值由调用方（`BookingService.resolveQuietWindow`）给出。
 *
 * ── 唯一的例外：管理员手动触发 ────────────────────────────────────────────
 * `POST /admin/tasks/*` 可带 `quietWindowMinutes` 覆盖**本次**扫描的静默期，默认仍是本常量。
 * 这是为测试服务的：不覆盖的话，「刚下的单」要干等 2 小时才会被扫到，链路根本没法验一遍。
 * **cron 路径不接受覆盖**，永远走默认值——A 规则本身没有被削弱。
 *
 * 已知并接受的后果：23:50 下单、00:13 被 T1 翻成过期的用户，当晚不推；
 * 次日 22:00 由 T2 ② 补推（届时 `createdAt` 早已满足）。状态照常流转、
 * 订单列表可见、退款入口照常可用——**通知是提醒手段，不是状态展示的唯一途径**。
 *
 * 不满足静默期的订单**不写** `expireNotifiedAt`，下一轮继续被扫到，到期后自然补发。
 */
export const MESSAGE_QUIET_WINDOW_MS = 2 * 60 * 60 * 1000;

/**
 * 手动覆盖静默期的上界（24 小时）
 *
 * 再大就等于把这两类通知整体静默掉——那是「关功能」而不是「调参」，
 * 真要关该走配置开关，不该借一个测试用的入参达成。
 *
 * 下界是 0（合法值 = 不设静默期），由调用方钳制。
 */
export const MESSAGE_QUIET_WINDOW_MAX_MS = 24 * 60 * 60 * 1000;

/**
 * 单轮扫描的发消息上限（§7b）
 *
 * 【为什么必须有上限】T1 步骤②/T2 是「扫历史积压」的形态：2A 上线时库里可能
 * 已经堆着几百条未通知的过期单，不加限制会在同一分钟把它们全部发出去
 * （相当于对全部历史用户同时轰炸，且会瞬间写满 SQLite 的单写者预算）。
 * 按 `expiredAt ASC` 每轮取一批，积压会**逐轮消化**而不是一次性倾泻。
 *
 * 【为什么是 200】§7b 的 `EXPLAIN QUERY PLAN` 就是按 `LIMIT 200` 验证的；
 * 单条消息一次 INSERT，200 条约占几十毫秒，远小于 1 小时的扫描间隔。
 */
export const MESSAGE_SCAN_BATCH_LIMIT = 200;
